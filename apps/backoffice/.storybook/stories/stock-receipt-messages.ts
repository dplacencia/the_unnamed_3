function withSharedCopy(locale: Locale) {
  const shared = creationMessages[locale];
  return {
    ...localized[locale],
    close: shared.close,
    cancel: shared.cancel,
    cancelChange: shared.cancel,
    advanced: shared.advanced,
    retry: shared.retry,
    resume: shared.resume,
    memory: shared.memory,
    discardTitle: shared.discardTitle,
    discardText: shared.discardText,
    discard: shared.discard,
    keepEditing: shared.keepEditing,
    unitLabels: shared.unitLabels,
    pieceSymbol: shared.pieceSymbol,
  };
}

export type ReceiptMessages = ReturnType<typeof withSharedCopy>;

